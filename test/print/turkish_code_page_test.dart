import 'dart:convert';

import 'package:flutter_test/flutter_test.dart';
import 'package:printly/src/print/printly_charset.dart';
import 'package:printly/src/print/turkish_code_page.dart';

void main() {
  // The 12 Turkish letters in a fixed order, reused across charsets.
  const String turkishLetters = 'çÇğĞıİöÖşŞüÜ';

  group('TurkishCodePage CP857 (turkish)', () {
    test('maps every Turkish letter to its verified CP857 byte', () {
      expect(
        TurkishCodePage.encode(turkishLetters, charset: PrintlyCharset.turkish),
        <int>[
          0x87, // ç
          0x80, // Ç
          0xA7, // ğ
          0xA6, // Ğ
          0x8D, // ı
          0x98, // İ
          0x94, // ö
          0x99, // Ö
          0x9F, // ş
          0x9E, // Ş
          0x81, // ü
          0x9A, // Ü
        ],
      );
    });

    test('encodes a realistic mixed string', () {
      // "Çağrı" → Ç a ğ r ı
      expect(
        TurkishCodePage.encode('Çağrı', charset: PrintlyCharset.turkish),
        <int>[0x80, 0x61, 0xA7, 0x72, 0x8D],
      );
    });

    test('passes ASCII through unchanged', () {
      expect(
        TurkishCodePage.encode('ABC-123', charset: PrintlyCharset.turkish),
        ascii.encode('ABC-123'),
      );
    });

    test('substitutes runes absent from CP857 with ?', () {
      // € (U+20AC) and an emoji are not in CP857.
      expect(
        TurkishCodePage.encode('€🎉', charset: PrintlyCharset.turkish),
        <int>[TurkishCodePage.unmappable, TurkishCodePage.unmappable],
      );
    });

    test('honours a custom replacement byte', () {
      expect(
        TurkishCodePage.encode(
          '€',
          charset: PrintlyCharset.turkish,
          replacement: 0x20,
        ),
        <int>[0x20],
      );
    });
  });

  group('TurkishCodePage Windows-1254', () {
    test('maps every Turkish letter to its WPC1254 byte', () {
      expect(
        TurkishCodePage.encode(
          turkishLetters,
          charset: PrintlyCharset.windows1254,
        ),
        <int>[
          0xE7, // ç
          0xC7, // Ç
          0xF0, // ğ
          0xD0, // Ğ
          0xFD, // ı
          0xDD, // İ
          0xF6, // ö
          0xD6, // Ö
          0xFE, // ş
          0xDE, // Ş
          0xFC, // ü
          0xDC, // Ü
        ],
      );
    });

    test('supports the euro sign in the C1 punctuation block', () {
      expect(
        TurkishCodePage.encode('€', charset: PrintlyCharset.windows1254),
        <int>[0x80],
      );
    });
  });

  group('TurkishCodePage ISO-8859-9', () {
    test('shares the high range with Windows-1254 for Turkish letters', () {
      expect(
        TurkishCodePage.encode(
          turkishLetters,
          charset: PrintlyCharset.iso8859_9,
        ),
        TurkishCodePage.encode(
          turkishLetters,
          charset: PrintlyCharset.windows1254,
        ),
      );
    });

    test('has no euro sign (substitutes ?)', () {
      expect(
        TurkishCodePage.encode('€', charset: PrintlyCharset.iso8859_9),
        <int>[TurkishCodePage.unmappable],
      );
    });
  });

  group('TurkishCodePage latin (CP437) & utf8', () {
    test(
      'latin keeps ASCII and CP437-shared Turkish letters, drops the rest',
      () {
        // CP437 contains ç/Ç/ö/Ö/ü/Ü but not the Turkish-specific
        // ş/ı/ğ/İ/Ş/Ğ, which stay '?'.
        expect(
          TurkishCodePage.encode('AğB', charset: PrintlyCharset.latin),
          <int>[0x41, TurkishCodePage.unmappable, 0x42],
        );
        expect(
          TurkishCodePage.encode('çÇöÖüÜ', charset: PrintlyCharset.latin),
          <int>[0x87, 0x80, 0x94, 0x99, 0x81, 0x9A],
        );
        expect(
          TurkishCodePage.encode('şıİŞĞ', charset: PrintlyCharset.latin),
          List<int>.filled(5, TurkishCodePage.unmappable),
        );
      },
    );

    test('latin encodes CP437 accents instead of substituting them', () {
      // é lives at 0x82 in CP437, so 'café' must survive intact.
      expect(
        TurkishCodePage.encode('café', charset: PrintlyCharset.latin),
        <int>[0x63, 0x61, 0x66, 0x82],
      );
      expect(
        TurkishCodePage.encode('üçö£', charset: PrintlyCharset.latin),
        <int>[0x81, 0x87, 0x94, 0x9C],
      );
    });

    test('utf8 emits multi-byte sequences verbatim', () {
      expect(
        TurkishCodePage.encode('ğ', charset: PrintlyCharset.utf8),
        utf8.encode('ğ'),
      );
      expect(utf8.encode('ğ'), <int>[0xC4, 0x9F]);
    });
  });

