  0x1B, 0x74, 0x00, 0x1B, 0x24, 0x00, 0x00, 0x1B, 0x61, 0x30, 0x1B, 0x45,
  0x00, 0x1C, 0x2E, 0x2D, 0x2D, 0x2D, 0x2D, 0x2D, 0x2D, 0x2D, 0x2D, 0x2D,
