import 'package:esc_pos_utils_plus/esc_pos_utils_plus.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:printly/printly.dart';

/// Full expected byte stream for the representative receipt below.
///
/// This golden pins the ESC/POS wire format against esc_pos_utils_plus
/// upgrades (and against accidental changes to printly's own emitters): a
/// dependency bump that changes any emitted byte fails this test instead of
/// silently changing what printers receive. Regenerate DELIBERATELY — build
/// the same receipt, dump `build()`, verify the diff byte-by-byte against the
/// ESC/POS spec, then update this constant.
// dart format off
