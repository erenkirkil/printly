// dart format on

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test(
    'representative receipt matches the committed golden byte stream',
    () async {
      final CapabilityProfile profile = await CapabilityProfile.load();
      final PrintJob receipt =
          PrintJob.fromGenerator(generator: Generator(PaperSize.mm58, profile))
            ..text(
              'MAĞAZA',
              align: PrintlyTextAlign.center,
              style: PrintlyTextStyle.bold,
              charset: PrintlyCharset.turkish,
            )
            ..divider()
            ..text('Teşekkürler', charset: PrintlyCharset.turkish)
            ..barcode('AB12', type: PrintlyBarcodeType.code128)
            ..qr('https://example.com')
            ..feed(2)
            ..cut();

      expect(receipt.build(), kGoldenReceiptBytes);
    },
  );
}
