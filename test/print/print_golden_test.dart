  0x65, 0x6B, 0x6B, 0x81, 0x72, 0x6C, 0x65, 0x72, 0x0A, 0x1B, 0x61, 0x31,
  // CODE128 barcode: GS H 2 (HRI below), GS w 3, GS h 60, GS k 73
