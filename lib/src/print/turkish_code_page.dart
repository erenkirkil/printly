/// Encodes Dart strings to the single-byte code pages thermal printers use for
/// Turkish text.
///
/// Dart's built-in `latin1` codec cannot represent the Turkish letters
/// `ğ Ğ ı İ ş Ş` at all and places `ç ö ü …` at byte positions that do not
/// match a printer's CP857/WPC1254 tables, so a dedicated lookup is required.
///
/// The primary table is **CP857** (IBM Turkish), the most widely supported
/// page. **Windows-1254** and **ISO-8859-9** are provided as fallbacks for
