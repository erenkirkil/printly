/// the project roadmap.
///
/// All encoders pass ASCII (`0x00–0x7F`) through unchanged and substitute any
/// rune they cannot represent with [unmappable] (`?`).
///
/// Stable public utility: exported from the package barrel so consumers can
/// pre-verify how a string will reach the printer; covered by semver like the
