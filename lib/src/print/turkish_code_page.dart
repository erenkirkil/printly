  /// The six positions where ISO-8859-9 / Windows-1254 replace ISO-8859-1's
  /// Icelandic letters with Turkish ones (`byte → Unicode`).
  static const Map<int, int> _latin5TurkishOverrides = <int, int>{
    0xD0: 0x011E, // Ğ
    0xDD: 0x0130, // İ
    0xDE: 0x015E, // Ş
    0xF0: 0x011F, // ğ
    0xFD: 0x0131, // ı
    0xFE: 0x015F, // ş
  };

  static final Map<int, int> _cp437RuneToByte = _invert(_cp437High);
  static final Map<int, int> _cp857RuneToByte = _invert(_cp857High);
  static final Map<int, int> _windows1254RuneToByte = _invert(
    _windows1254ByteToRune(),
  );
  static final Map<int, int> _iso8859_9RuneToByte = _invert(
    _iso8859_9ByteToRune(),
  );

  /// Encodes [text] for [charset], returning the printer-ready bytes.
  ///
  /// ASCII passes through unchanged. For [PrintlyCharset.utf8] the string is
  /// UTF-8 encoded verbatim. For every other charset each rune is looked up in
  /// the corresponding code-page table and runes with no representation are
  /// replaced with [replacement] (defaults to [unmappable], `?`).
  static Uint8List encode(
    String text, {
    required PrintlyCharset charset,
    int replacement = unmappable,
  }) {
    if (charset == PrintlyCharset.utf8) {
      return Uint8List.fromList(utf8.encode(text));
    }

    final Map<int, int>? table = switch (charset) {
      PrintlyCharset.turkish => _cp857RuneToByte,
      PrintlyCharset.windows1254 => _windows1254RuneToByte,
      PrintlyCharset.iso8859_9 => _iso8859_9RuneToByte,
      PrintlyCharset.latin => _cp437RuneToByte,
      PrintlyCharset.utf8 => null,
    };

    final BytesBuilder out = BytesBuilder(copy: false);
    for (final int rune in text.runes) {
      if (rune < 0x80) {
        out.addByte(rune);
      } else {
        out.addByte(table?[rune] ?? replacement);
      }
    }
    return out.toBytes();
  }

  /// Builds the full Windows-1254 `byte → rune` map.
  static Map<int, int> _windows1254ByteToRune() {
    final Map<int, int> map = <int, int>{..._windows1254Punctuation};
    for (int b = 0xA0; b <= 0xFF; b++) {
      map[b] = _latin5TurkishOverrides[b] ?? b;
    }
    return map;
  }

  /// Builds the full ISO-8859-9 `byte → rune` map (Latin-1 with the six
  /// Turkish overrides; the `0x80–0x9F` C1 range stays identity).
  static Map<int, int> _iso8859_9ByteToRune() {
    final Map<int, int> map = <int, int>{};
    for (int b = 0x80; b <= 0xFF; b++) {
      map[b] = _latin5TurkishOverrides[b] ?? b;
    }
    return map;
  }

  /// Inverts a `byte → rune` map into `rune → byte`. When two bytes map to the
  /// same rune the lower byte wins, which keeps encoding deterministic.
  static Map<int, int> _invert(Map<int, int> byteToRune) {
    final Map<int, int> runeToByte = <int, int>{};
    for (final MapEntry<int, int> entry in byteToRune.entries) {
      runeToByte.putIfAbsent(entry.value, () => entry.key);
    }
    return runeToByte;
  }
